const buildPatternCells = (
  condition: (
    row: number,
    col: number
  ) => boolean
): number[] => {

  const cells: number[] = [];

  for (
    let row = 0;
    row < 5;
    row += 1
  ) {

    for (
      let col = 0;
      col < 5;
      col += 1
    ) {

      if (
        condition(
          row,
          col
        )
      ) {

        cells.push(
          row * 5 + col
        );

      }

    }

  }

  return cells;
};


