/* =========================================================
   3 CORNER DOTS + 2 DISCONNECTED SQUARES
========================================================= */

const THREE_CORNER_DOTS_TWO_SQUARE_LAYOUTS:
  number[][] = [];


for (
  let missingCornerIndex = 0;
  missingCornerIndex <
  CORNER_CELLS.length;
  missingCornerIndex += 1
) {

  const selectedCornerDots =
    CORNER_CELLS.filter(
      (_, index) =>
        index !==
        missingCornerIndex
    );


  for (
    let i = 0;
    i <
    SQUARE_2X2_LAYOUTS.length;
    i += 1
  ) {

    const square1 =
      SQUARE_2X2_LAYOUTS[i];


    const square1Valid =
      square1.every(
        (cellIndex) =>
          !selectedCornerDots.includes(
            cellIndex
          )
      );


    if (!square1Valid) {
      continue;
    }


    for (
      let j = i + 1;
      j <
      SQUARE_2X2_LAYOUTS.length;
      j += 1
    ) {

      const square2 =
        SQUARE_2X2_LAYOUTS[j];


      const square2Valid =
        square2.every(
          (cellIndex) =>
            !selectedCornerDots.includes(
              cellIndex
            )
        );


      if (!square2Valid) {
        continue;
      }


      const squaresDisconnected =
        square1.every(
          (cellIndex) =>
            !square2.includes(
              cellIndex
            )
        );


      if (
        !squaresDisconnected
      ) {
        continue;
      }


      THREE_CORNER_DOTS_TWO_SQUARE_LAYOUTS.push(
        mergeCells(
          selectedCornerDots,
          square1,
          square2
        )
      );

    }

  }

}
/* =========================================================
   3 CORNER DOTS + 3 DISCONNECTED SQUARES

   Rules:
   - any 3 of the 4 corner dots
   - any 3 completed 2x2 squares
   - squares cannot overlap each other
   - squares cannot use selected corner dots
   - unused fourth corner may be used
========================================================= */

const THREE_CORNER_DOTS_THREE_SQUARE_LAYOUTS:
  number[][] = [];


for (
  let missingCornerIndex = 0;
  missingCornerIndex <
  CORNER_CELLS.length;
  missingCornerIndex += 1
) {

  const selectedCornerDots =
    CORNER_CELLS.filter(
      (_, index) =>
        index !==
        missingCornerIndex
    );


  for (
    let i = 0;
    i <
    SQUARE_2X2_LAYOUTS.length;
    i += 1
  ) {

    const square1 =
      SQUARE_2X2_LAYOUTS[i];


    const square1Valid =
      square1.every(
        (cellIndex) =>
          !selectedCornerDots.includes(
            cellIndex
          )
      );


    if (!square1Valid) {
      continue;
    }


    for (
      let j = i + 1;
      j <
      SQUARE_2X2_LAYOUTS.length;
      j += 1
    ) {

      const square2 =
        SQUARE_2X2_LAYOUTS[j];


      const square2Valid =
        square2.every(
          (cellIndex) =>
            !selectedCornerDots.includes(
              cellIndex
            )
        ) &&
        square2.every(
          (cellIndex) =>
            !square1.includes(
              cellIndex
            )
        );


      if (!square2Valid) {
        continue;
      }


      for (
        let k = j + 1;
        k <
        SQUARE_2X2_LAYOUTS.length;
        k += 1
      ) {

        const square3 =
          SQUARE_2X2_LAYOUTS[k];


        const square3Valid =
          square3.every(
            (cellIndex) =>
              !selectedCornerDots.includes(
                cellIndex
              )
          ) &&
          square3.every(
            (cellIndex) =>
              !square1.includes(
                cellIndex
              ) &&
              !square2.includes(
                cellIndex
              )
          );


        if (!square3Valid) {
          continue;
        }


        THREE_CORNER_DOTS_THREE_SQUARE_LAYOUTS.push(
          mergeCells(
            selectedCornerDots,
            square1,
            square2,
            square3
          )
        );

      }

    }

  }

}
