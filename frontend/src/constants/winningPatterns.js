/* =========================================
   GET LABEL BY LANGUAGE
========================================= */

export const getWinningPatternLabel = (
  value,
  language = "am"
) => {

  const pattern =
    WINNING_PATTERNS.find(
      (item) =>
        item.value === value
    );


  if (!pattern) {
    return value;
  }


  return (
    pattern.label?.[
      language
    ] ||
    pattern.label?.am ||
    pattern.label?.en ||
    value
  );
};